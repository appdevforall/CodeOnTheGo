package com.itsaky.androidide.app

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import com.google.common.truth.Truth.assertThat
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.File

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [29])
class AppWipeServiceTest {
	private val context: Context = ApplicationProvider.getApplicationContext()

	@Test
	fun `the wipe deletes the relocated build output and Quick Build's scratch`() {
		val targets = AppWipeService(context).buildPlan().fastDeleteTargets

		assertThat(targets).containsAtLeast(
			File(context.noBackupFilesDir, "gradle-build"),
			File(context.noBackupFilesDir, "quickbuild-scratch"),
		)
	}
}
