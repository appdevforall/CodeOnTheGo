package com.itsaky.androidide.plugins.build

import com.google.common.truth.Truth.assertThat
import org.junit.jupiter.api.Test
import java.io.StringReader
import java.util.Properties

/** Covers the shape and the determinism of the provenance record packaged into every `.cgp`. */
class CgpBuildPropertiesTest {
	@Test
	fun givenAFullRecord_whenRendering_thenEveryFieldIsReadableAsAPropertiesFile() {
		val rendered = render(libsRevision = "ee6d454f7e16")
		val parsed = parse(rendered)

		assertThat(parsed["name"]).isEqualTo("random-xkcd")
		assertThat(parsed["version"]).isEqualTo("1.0.0-release.20260901161500")
		assertThat(parsed["variant"]).isEqualTo("release")
		assertThat(parsed["revision"]).isEqualTo("0c505c6c4d2f")
		assertThat(parsed["revision_source"]).isEqualTo("git")
		assertThat(parsed["libs_revision"]).isEqualTo("ee6d454f7e16")
		assertThat(parsed["timestamp"]).isEqualTo("20260901161500")
		assertThat(parsed["timestamp_source"]).isEqualTo("commit")
	}

	@Test
	fun givenNoLibsRevision_whenRendering_thenTheKeyIsOmittedRatherThanEmpty() {
		val rendered = render(libsRevision = null)

		assertThat(rendered).doesNotContain("libs_revision")
		assertThat(parse(rendered).keys).hasSize(7)
	}

	@Test
	fun givenTheSameRecordTwice_whenRendering_thenTheOutputIsByteIdentical() {
		assertThat(render(libsRevision = "ee6d454f7e16")).isEqualTo(render(libsRevision = "ee6d454f7e16"))
	}

	@Test
	fun givenAnyRecord_whenRendering_thenTheOnlyCommentIsTheFixedHeader() {
		// java.util.Properties.store() stamps the current date into its output, which would make
		// two builds of one commit produce two different .cgp files.
		val comments = render(libsRevision = null).lines().filter { it.startsWith("#") }

		assertThat(comments).containsExactly("# Generated by the Code on the Go plugin builder. Do not edit.")
	}

	@Test
	fun givenAPluginNameWithSeparators_whenRendering_thenItRoundTripsIntact() {
		val rendered = render(pluginName = "weird=name:with\\separators")

		assertThat(parse(rendered)["name"]).isEqualTo("weird=name:with\\separators")
	}

	@Test
	fun givenAnUnresolvedBuild_whenRendering_thenTheRecordStillStatesSoExplicitly() {
		val rendered =
			CgpBuildProperties.render(
				pluginName = "community-plugin",
				version = "1.0.0-release.20260901161500",
				variantName = "release",
				provenance =
					record(
						revision = PluginProvenance.UNKNOWN_REVISION,
						revisionSource = RevisionSource.NONE.id,
						timestampSource = TimestampSource.WALL_CLOCK,
					),
			)
		val parsed = parse(rendered)

		assertThat(parsed["revision"]).isEqualTo("unknown")
		assertThat(parsed["revision_source"]).isEqualTo("none")
		assertThat(parsed["timestamp_source"]).isEqualTo("wall-clock")
	}

	@Test
	fun givenANonAsciiPluginName_whenRendering_thenItSurvivesTheIso88591LoadPath() {
		// Properties.load(InputStream) decodes ISO-8859-1 while the file is written as UTF-8, so
		// a bare non-ASCII character would come back as mojibake on the standard read path.
		val rendered = render(pluginName = "caf\u00e9-\u30d7\u30e9\u30b0\u30a4\u30f3")
		val properties = Properties()
		rendered.byteInputStream(Charsets.UTF_8).use(properties::load)

		assertThat(rendered).doesNotContain("caf\u00e9")
		assertThat(properties.getProperty("name")).isEqualTo("caf\u00e9-\u30d7\u30e9\u30b0\u30a4\u30f3")
	}

	private fun render(
		libsRevision: String? = null,
		pluginName: String = "random-xkcd",
	) = CgpBuildProperties.render(
		pluginName = pluginName,
		version = "1.0.0-release.20260901161500",
		variantName = "release",
		provenance = record(libsRevision = libsRevision),
	)

	private fun record(
		revision: String = "0c505c6c4d2f",
		revisionSource: String = RevisionSource.GIT_COMMAND.id,
		timestampSource: TimestampSource = TimestampSource.COMMIT,
		libsRevision: String? = null,
	) = PluginProvenanceRecord(
		revision = revision,
		revisionSource = revisionSource,
		timestamp = "20260901161500",
		timestampSource = timestampSource,
		libsRevision = libsRevision,
	)

	private fun parse(rendered: String): Map<String, String> {
		val properties = Properties()
		StringReader(rendered).use(properties::load)
		return properties.entries.associate { (key, value) -> key.toString() to value.toString() }
	}
}
