package com.itsaky.androidide.plugins.build

import org.gradle.api.provider.Property

abstract class PluginBuilderExtension {
	abstract val pluginName: Property<String>

	abstract val pluginVersion: Property<String>

	/**
	 * Commit the plugin is built from, when the build cannot discover it itself.
	 *
	 * The escape hatch for source drops: a tarball, a `git archive` export, or a foreign CI whose
	 * env vars this builder does not know. Setting it wins over every other step of the chain and
	 * is recorded as `revision_source=explicit`, so a reader can tell a stated revision from a
	 * discovered one.
	 */
	abstract val pluginVcsRevision: Property<String>

	/**
	 * Whether to append the revision to an autogenerated version string. Off by default.
	 *
	 * The revision's real home is the `plugin.vcs_revision` manifest entry: the plugin list's
	 * version chip truncates anything past the third dot-segment, so a revision inside the version
	 * string is invisible where it matters.
	 */
	abstract val includeRevisionInVersion: Property<Boolean>
}
