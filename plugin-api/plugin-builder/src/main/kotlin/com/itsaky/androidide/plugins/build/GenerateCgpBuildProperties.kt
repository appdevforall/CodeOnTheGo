package com.itsaky.androidide.plugins.build

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/** Renders the provenance record packaged into every `.cgp`. */
object CgpBuildProperties {
	/**
	 * Packaged at `assets/cgp-build.properties`, i.e. inside the APK before signing, so it is
	 * covered by the v2/v3 signature and readable through the plugin's own `AssetManager`.
	 * Appending it to the finished archive instead would invalidate that signature and, for a
	 * plugin bundling native libraries, rewrite a ~100 MB zip on every build.
	 */
	const val FILE_NAME = "cgp-build.properties"

	private val PRINTABLE_ASCII = 0x20..0x7E

	/**
	 * A fixed key order and no generated comment, because [java.util.Properties.store] stamps the
	 * current date into its output -- which would make the file, and therefore the `.cgp`, differ
	 * between two builds of the same commit.
	 */
	fun render(
		pluginName: String,
		version: String,
		variantName: String,
		provenance: PluginProvenanceRecord,
	): String {
		val fields =
			buildList {
				add("name" to pluginName)
				add("version" to version)
				add("variant" to variantName)
				add("revision" to provenance.revision)
				add("revision_source" to provenance.revisionSource)
				provenance.libsRevision?.let { add("libs_revision" to it) }
				add("timestamp" to provenance.timestamp)
				add("timestamp_source" to provenance.timestampSource.id)
			}

		return buildString {
			append("# Generated by the Code on the Go plugin builder. Do not edit.\n")
			for ((key, value) in fields) {
				append(key).append('=').append(escape(value)).append('\n')
			}
		}
	}

	/**
	 * `java.util.Properties.load(InputStream)` decodes ISO-8859-1, but the file is written as
	 * UTF-8, so anything outside printable ASCII has to go out as a `\uXXXX` escape or a reader
	 * taking that standard path sees mojibake. Control characters are escaped for the same reason.
	 */
	private fun escape(value: String): String =
		buildString(value.length) {
			for (ch in value) {
				when {
					ch == '\\' -> append("\\\\")
					ch == '\n' -> append("\\n")
					ch == '\r' -> append("\\r")
					ch == '\t' -> append("\\t")
					ch.code in PRINTABLE_ASCII -> append(ch)
					else -> append("\\u").append("%04x".format(ch.code))
				}
			}
		}
}

/**
 * Writes `cgp-build.properties` into a generated assets directory wired into the variant's asset
 * sources, so AGP packages and signs it with everything else.
 *
 * The file is always written, even when nothing could be resolved: a present record saying
 * `revision=unknown` is a statement, whereas a missing file is ambiguous between an old builder,
 * a community build, and tampering.
 */
abstract class GenerateCgpBuildProperties : DefaultTask() {
	@get:Input
	abstract val pluginName: Property<String>

	@get:Input
	abstract val pluginVersion: Property<String>

	@get:Input
	abstract val variantName: Property<String>

	@get:Input
	abstract val revision: Property<String>

	@get:Input
	abstract val revisionSource: Property<String>

	@get:Input
	abstract val buildTimestamp: Property<String>

	@get:Input
	abstract val timestampSource: Property<TimestampSource>

	@get:Input
	@get:Optional
	abstract val libsRevision: Property<String>

	@get:OutputDirectory
	abstract val outputDir: DirectoryProperty

	init {
		group = "build"
		description = "Generates the ${CgpBuildProperties.FILE_NAME} provenance record for the plugin"
	}

	@TaskAction
	fun generate() {
		val target = outputDir.get().asFile
		target.mkdirs()
		target.resolve(CgpBuildProperties.FILE_NAME).writeText(
			CgpBuildProperties.render(
				pluginName = pluginName.get(),
				version = pluginVersion.get(),
				variantName = variantName.get(),
				provenance =
					PluginProvenanceRecord(
						revision = revision.get(),
						revisionSource = revisionSource.get(),
						timestamp = buildTimestamp.get(),
						timestampSource = timestampSource.get(),
						libsRevision = libsRevision.orNull,
					),
			),
		)
	}
}
