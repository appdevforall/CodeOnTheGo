package com.itsaky.androidide.plugins.tasks

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Generates `:app`'s `BuildConfig` class in place of AGP's (ADFA-6954).
 *
 * AGP's `BuildConfig` for an app also holds `VERSION_CODE` and `VERSION_NAME`. Ours change on every
 * commit (the version name is the commit time) and every hour (the version code). The class is
 * compiled with the rest of `:app`, so with AGP's class, every new commit re-ran `:app`'s kapt,
 * Kotlin and Java compiles and dexing. This class has the same name and AGP's other fields (see
 * [appBuildConfigSource]), so no call site changes. The version is still in the manifest. At
 * runtime, read the version name from `BuildInfo.VERSION_NAME_SIMPLE` in `:build-info`, or the
 * name and code from `PackageManager`.
 */
@DisableCachingByDefault(because = "Writes one small file; regenerating it is faster than a cache lookup")
abstract class GenerateAppBuildConfigTask : DefaultTask() {
	@get:Input
	abstract val packageName: Property<String>

	@get:Input
	abstract val debuggable: Property<Boolean>

	@get:Input
	abstract val applicationId: Property<String>

	@get:Input
	abstract val buildTypeName: Property<String>

	@get:Input
	abstract val flavorName: Property<String>

	/** Extra `String` fields, as AGP's `buildConfigField` would add them. */
	@get:Input
	abstract val stringFields: MapProperty<String, String>

	@get:OutputDirectory
	abstract val outputDir: DirectoryProperty

	@TaskAction
	fun generate() {
		val pkg = packageName.get()
		val root = outputDir.get().asFile
		root.deleteRecursively()
		val file = root.resolve(pkg.replace('.', '/')).resolve("BuildConfig.java")
		file.parentFile.mkdirs()
		file.writeText(
			appBuildConfigSource(
				packageName = pkg,
				debuggable = debuggable.get(),
				applicationId = applicationId.get(),
				buildType = buildTypeName.get(),
				flavor = flavorName.get(),
				stringFields = stringFields.get(),
			),
		)
	}
}

/**
 * The text of `:app`'s `BuildConfig`: what AGP 8.8's `GenerateBuildConfig` writes, without
 * `VERSION_CODE` and `VERSION_NAME`, and with two more header lines saying why.
 */
internal fun appBuildConfigSource(
	packageName: String,
	debuggable: Boolean,
	applicationId: String,
	buildType: String,
	flavor: String,
	stringFields: Map<String, String>,
): String =
	buildString {
		appendLine("/**")
		appendLine(" * Automatically generated file. DO NOT MODIFY")
		appendLine(" *")
		appendLine(" * Generated by GenerateAppBuildConfigTask, not by AGP: it leaves out VERSION_CODE and")
		appendLine(" * VERSION_NAME, so a new commit doesn't recompile :app (ADFA-6954).")
		appendLine(" */")
		appendLine("package $packageName;")
		appendLine()
		appendLine("public final class BuildConfig {")
		// AGP's two forms: only `false` is a constant, so compilers drop `if (DEBUG)` code in release builds.
		val debug = if (debuggable) "Boolean.parseBoolean(\"true\")" else "false"
		appendLine("  public static final boolean DEBUG = $debug;")
		appendLine("  public static final String APPLICATION_ID = ${javaString(applicationId)};")
		appendLine("  public static final String BUILD_TYPE = ${javaString(buildType)};")
		if (flavor.isNotEmpty()) {
			appendLine("  public static final String FLAVOR = ${javaString(flavor)};")
		}
		stringFields.toSortedMap().forEach { (name, value) ->
			appendLine("  // Field from default config.")
			appendLine("  public static final String $name = ${javaString(value)};")
		}
		appendLine("}")
	}

private fun javaString(value: String): String = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
